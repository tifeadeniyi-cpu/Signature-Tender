'use client';
import { useMemo, useRef, useState, type PointerEvent as RPointerEvent } from 'react';
import {
  CANVAS_H,
  CANVAS_W,
  DEFAULT_SMART,
  newElement,
  toSvg,
  type Anchor,
  type Design,
  type Point,
  type Rendered,
} from '@st/core/studio/index';
import { cn } from '@/lib/cn';
import { clamp, newId, round1, toDesign, toDrawingSpace, toLocal, updateElement, type DesignHistory } from './state';

export type CanvasMode = 'select' | 'draw' | 'freehand' | 'curve';
export type Background = 'white' | 'ivory' | 'navy' | 'field' | 'transparent';

export const BACKGROUNDS: { id: Background; label: string }[] = [
  { id: 'white', label: 'White paper' },
  { id: 'ivory', label: 'Warm ivory' },
  { id: 'navy', label: 'Dark navy' },
  { id: 'field', label: 'PDF signature field' },
  { id: 'transparent', label: 'Transparent' },
];

const CHECKER =
  'repeating-conic-gradient(#e5e7eb 0% 25%, #ffffff 0% 50%) 50% / 20px 20px';

export function backgroundStyle(bg: Background): React.CSSProperties {
  switch (bg) {
    case 'ivory':
      return { background: '#FFF9F2' };
    case 'navy':
      return { background: '#0D1B33' };
    case 'transparent':
      return { background: CHECKER };
    default:
      return { background: '#FFFFFF' };
  }
}

/** Renders a design as inline SVG (paths only, generated by our own renderer). */
export function ArtworkSvg({
  rendered,
  imageHref,
  full,
  className,
  label,
}: {
  rendered: Rendered;
  imageHref?: (ref: string) => string | undefined;
  /** Use the whole editing canvas as the view box instead of cropping to the artwork. */
  full?: boolean;
  className?: string;
  label?: string;
}) {
  const svg = useMemo(
    () => toSvg(rendered, { imageHref, ...(full ? { viewBox: { minX: 0, minY: 0, maxX: CANVAS_W, maxY: CANVAS_H } } : {}) }),
    [rendered, imageHref, full],
  );
  return (
    <div
      role="img"
      aria-label={label ?? 'Signature preview'}
      className={cn('[&>svg]:block [&>svg]:h-auto [&>svg]:max-h-full [&>svg]:w-full', className)}
      dangerouslySetInnerHTML={{ __html: svg }}
    />
  );
}

type Drag =
  | { kind: 'move'; target: string; sx: number; sy: number; start: Design }
  | { kind: 'scale'; target: string; cx: number; cy: number; d0: number; start: Design }
  | { kind: 'rotate'; target: string; cx: number; cy: number; a0: number; start: Design }
  | { kind: 'ink'; points: Point[] }
  | { kind: 'anchor'; index: number; part: 'p' | 'i' | 'o'; start: Design };

interface Props {
  history: DesignHistory;
  rendered: Rendered;
  imageHref?: (ref: string) => string | undefined;
  mode: CanvasMode;
  selected: string | null;
  onSelect: (id: string | null) => void;
  anchorIndex: number | null;
  onAnchor: (i: number | null) => void;
  background: Background;
  zoom: number;
  /** Shows the "Preview" marker over unpurchased designs. */
  marker: boolean;
  onStrokeAdded?: (elementId: string) => void;
}

export function StudioCanvas({
  history,
  rendered,
  imageHref,
  mode,
  selected,
  onSelect,
  anchorIndex,
  onAnchor,
  background,
  zoom,
  marker,
  onStrokeAdded,
}: Props) {
  const { design } = history;
  const svgRef = useRef<SVGSVGElement>(null);
  const drag = useRef<Drag | null>(null);
  const [live, setLive] = useState<Point[] | null>(null);

  const toCanvas = (e: { clientX: number; clientY: number }): [number, number] => {
    const svg = svgRef.current!;
    const pt = svg.createSVGPoint();
    pt.x = e.clientX;
    pt.y = e.clientY;
    const m = svg.getScreenCTM();
    if (!m) return [0, 0];
    const p = pt.matrixTransform(m.inverse());
    return [p.x, p.y];
  };

  const boxFor = (id: string) =>
    id === 'text' ? rendered.boxes.text : id === 'drawing' ? rendered.boxes.drawing : id === 'upload' ? rendered.boxes.upload : rendered.boxes.elements[id];

  const sel = selected ? boxFor(selected) : undefined;
  const selEl = design.elements.find((e) => e.id === selected);
  const valid = (b?: { minX: number }) => b && isFinite(b.minX);

  function hitTest(x: number, y: number): string | null {
    const pad = 8;
    const order = [...design.elements].reverse().map((e) => e.id);
    for (const id of [...order, 'text', 'drawing', 'upload']) {
      const b = boxFor(id);
      if (b && isFinite(b.minX) && x >= b.minX - pad && x <= b.maxX + pad && y >= b.minY - pad && y <= b.maxY + pad) return id;
    }
    return null;
  }

  function moveTarget(d: Design, target: string, dx: number, dy: number): Design {
    if (target === 'text' && d.text) return { ...d, text: { ...d.text, x: round1(d.text.x + dx), y: round1(d.text.y + dy) } };
    if (target === 'drawing') return { ...d, drawing: { ...d.drawing, x: round1(clamp(d.drawing.x + dx, -1200, 1200)), y: round1(clamp(d.drawing.y + dy, -400, 400)) } };
    if (target === 'upload' && d.upload) return { ...d, upload: { ...d.upload, x: round1(d.upload.x + dx), y: round1(d.upload.y + dy) } };
    const e = d.elements.find((x) => x.id === target);
    return e ? updateElement(d, target, { x: round1(clamp(e.x + dx, -600, 1800)), y: round1(clamp(e.y + dy, -400, 800)) }) : d;
  }

  function onDown(ev: RPointerEvent<SVGSVGElement>) {
    if (ev.button !== 0 && ev.pointerType === 'mouse') return;
    const [x, y] = toCanvas(ev);
    (ev.target as Element).setPointerCapture?.(ev.pointerId);
    const role = (ev.target as Element).getAttribute('data-role');
    if (mode === 'draw' || mode === 'freehand') {
      drag.current = { kind: 'ink', points: [[round1(x), round1(y), pressureOf(ev)]] };
      setLive([[x, y, 0.5]]);
      return;
    }
    if (role === 'anchor' || role === 'handle-i' || role === 'handle-o') {
      const index = Number((ev.target as Element).getAttribute('data-index'));
      onAnchor(index);
      drag.current = { kind: 'anchor', index, part: role === 'anchor' ? 'p' : role === 'handle-i' ? 'i' : 'o', start: design };
      return;
    }
    if (selected && sel && valid(sel) && (role === 'scale' || role === 'rotate')) {
      const cx = (sel.minX + sel.maxX) / 2;
      const cy = (sel.minY + sel.maxY) / 2;
      drag.current =
        role === 'scale'
          ? { kind: 'scale', target: selected, cx, cy, d0: Math.hypot(x - cx, y - cy) || 1, start: design }
          : { kind: 'rotate', target: selected, cx, cy, a0: Math.atan2(y - cy, x - cx), start: design };
      return;
    }
    const hit = hitTest(x, y);
    onSelect(hit);
    if (hit) drag.current = { kind: 'move', target: hit, sx: x, sy: y, start: design };
  }

  function onMove(ev: RPointerEvent<SVGSVGElement>) {
    const g = drag.current;
    if (!g) return;
    const [x, y] = toCanvas(ev);
    if (g.kind === 'ink') {
      const last = g.points[g.points.length - 1]!;
      if (Math.hypot(x - last[0], y - last[1]) < 1.5) return;
      if (g.points.length >= 3900) return;
      g.points.push([round1(x), round1(y), pressureOf(ev)]);
      setLive([...g.points]);
      return;
    }
    if (g.kind === 'move') {
      history.replace(moveTarget(g.start, g.target, x - g.sx, y - g.sy), false);
      return;
    }
    if (g.kind === 'scale' || g.kind === 'rotate') {
      const d = g.start;
      const f = g.kind === 'scale' ? Math.hypot(x - g.cx, y - g.cy) / g.d0 : 1;
      const da = g.kind === 'rotate' ? ((Math.atan2(y - g.cy, x - g.cx) - g.a0) * 180) / Math.PI : 0;
      const wrap = (a: number) => round1(((a + 540) % 360) - 180);
      if (g.target === 'text' && d.text) {
        const p = d.text.params;
        history.replace({ ...d, text: { ...d.text, params: { ...p, height: round1(clamp(p.height * f, 0.6, 1.5) * 100) / 100 } } }, false);
      } else if (g.target === 'drawing') {
        history.replace({ ...d, drawing: { ...d.drawing, scale: clamp(d.drawing.scale * f, 0.2, 4), rotate: wrap(d.drawing.rotate + da) } }, false);
      } else if (g.target === 'upload' && d.upload) {
        history.replace({ ...d, upload: { ...d.upload, scale: clamp(d.upload.scale * f, 0.05, 6), rotate: wrap(d.upload.rotate + da) } }, false);
      } else {
        const e = d.elements.find((q) => q.id === g.target);
        if (e) history.replace(updateElement(d, e.id, { scale: round1(clamp(e.scale * f, 0.1, 3) * 100) / 100, rotate: wrap(e.rotate + da) }), false);
      }
      return;
    }
    if (g.kind === 'anchor' && selEl?.anchors) {
      const [lx, ly] = toLocal(selEl, x, y);
      const anchors = selEl.anchors.map((a, i): Anchor => {
        if (i !== g.index) return a;
        if (g.part === 'p') return { ...a, x: round1(lx), y: round1(ly) };
        if (g.part === 'i') return { ...a, ix: round1(lx - a.x), iy: round1(ly - a.y), ox: round1(-(lx - a.x)), oy: round1(-(ly - a.y)) };
        return { ...a, ox: round1(lx - a.x), oy: round1(ly - a.y), ix: round1(-(lx - a.x)), iy: round1(-(ly - a.y)) };
      });
      history.replace(updateElement(g.start, selEl.id, { anchors }), false);
    }
  }

  function onUp() {
    const g = drag.current;
    drag.current = null;
    if (!g) return;
    if (g.kind === 'ink') {
      setLive(null);
      if (g.points.length < 2) return;
      if (mode === 'draw') {
        const pts = g.points.map(([x, y, p]): Point => {
          const [dx, dy] = toDrawingSpace(design, x, y);
          return [round1(dx), round1(dy), p];
        });
        history.set((d) => ({ ...d, method: d.method === 'design' ? 'design' : 'draw', strokes: [...d.strokes, { points: pts, smooth: 0 }] }));
      } else {
        const [ox, oy] = g.points[0]!;
        const id = newId();
        const el = {
          ...newElement('freehand', id, { x: round1(ox), y: round1(oy), scale: 1 }),
          points: g.points.map(([x, y, p]): Point => [round1(x - ox), round1(y - oy), p]),
          smart: { ...DEFAULT_SMART },
        };
        history.set((d) => ({ ...d, elements: [...d.elements, el].slice(0, 40) }));
        onSelect(id);
        onStrokeAdded?.(id);
      }
      return;
    }
    history.endDrag();
  }

  const handle = 14;
  const anchorPts =
    mode === 'curve' && selEl?.anchors
      ? selEl.anchors.map((a) => ({
          p: toDesign(selEl, a.x, a.y),
          i: toDesign(selEl, a.x + a.ix, a.y + a.iy),
          o: toDesign(selEl, a.x + a.ox, a.y + a.oy),
        }))
      : [];
  const drawing = mode === 'draw' || mode === 'freehand';
  const isNavy = background === 'navy';

  return (
    <div
      className={cn(
        'relative overflow-hidden rounded-xl border border-border',
        background === 'field' && 'bg-white p-6',
      )}
      style={background === 'field' ? undefined : backgroundStyle(background)}
    >
      <div
        className="relative mx-auto origin-top transition-[width]"
        style={{ width: `${Math.round(zoom * 100)}%`, maxWidth: zoom > 1 ? 'none' : undefined }}
      >
        {background === 'field' ? (
          <div aria-hidden className="pointer-events-none absolute inset-x-[6%] bottom-[22%] border-b-2 border-dashed border-slate-400" />
        ) : null}
        <ArtworkSvg rendered={rendered} imageHref={imageHref} full className={cn(isNavy && '[&_path]:fill-white')} />
        {marker ? (
          <span
            aria-hidden
            className="pointer-events-none absolute inset-0 flex select-none items-center justify-center text-[clamp(1.5rem,6vw,4rem)] font-semibold uppercase tracking-[0.5em] text-slate-400/15"
            style={{ transform: 'rotate(-12deg)' }}
          >
            Preview
          </span>
        ) : null}
        <svg
          ref={svgRef}
          viewBox={`0 0 ${CANVAS_W} ${CANVAS_H}`}
          className={cn('absolute inset-0 h-full w-full', drawing ? 'cursor-crosshair touch-none' : 'touch-pan-y')}
          onPointerDown={onDown}
          onPointerMove={onMove}
          onPointerUp={onUp}
          onPointerCancel={onUp}
          aria-label={drawing ? 'Drawing area: draw with your mouse, finger or stylus' : 'Signature canvas: drag to move the selected part'}
          role="application"
        >
          <rect width={CANVAS_W} height={CANVAS_H} fill="transparent" />
          {!drawing && sel && valid(sel) ? (
            <g pointerEvents="visiblePainted">
              <rect
                x={sel.minX - 6}
                y={sel.minY - 6}
                width={sel.maxX - sel.minX + 12}
                height={sel.maxY - sel.minY + 12}
                fill="none"
                stroke="#D8AF68"
                strokeWidth={2}
                strokeDasharray="6 4"
                pointerEvents="none"
              />
              <rect
                data-role="scale"
                x={sel.maxX + 6 - handle / 2}
                y={sel.maxY + 6 - handle / 2}
                width={handle}
                height={handle}
                rx={3}
                fill="#FFFFFF"
                stroke="#0D1B33"
                strokeWidth={2}
                className="cursor-nwse-resize"
              />
              {selected !== 'text' ? (
                <circle
                  data-role="rotate"
                  cx={(sel.minX + sel.maxX) / 2}
                  cy={sel.minY - 30}
                  r={handle / 2 + 1}
                  fill="#FFFFFF"
                  stroke="#0D1B33"
                  strokeWidth={2}
                  className="cursor-grab"
                />
              ) : null}
            </g>
          ) : null}
          {anchorPts.map((a, i) => (
            <g key={i}>
              <line x1={a.i[0]} y1={a.i[1]} x2={a.o[0]} y2={a.o[1]} stroke="#94A3B8" strokeWidth={1.5} />
              <circle data-role="handle-i" data-index={i} cx={a.i[0]} cy={a.i[1]} r={7} fill="#FFFFFF" stroke="#475569" strokeWidth={2} />
              <circle data-role="handle-o" data-index={i} cx={a.o[0]} cy={a.o[1]} r={7} fill="#FFFFFF" stroke="#475569" strokeWidth={2} />
              <rect
                data-role="anchor"
                data-index={i}
                x={a.p[0] - 8}
                y={a.p[1] - 8}
                width={16}
                height={16}
                fill={anchorIndex === i ? '#D8AF68' : '#FFFFFF'}
                stroke="#0D1B33"
                strokeWidth={2}
              />
            </g>
          ))}
          {live ? (
            <polyline
              points={live.map((p) => `${p[0]},${p[1]}`).join(' ')}
              fill="none"
              stroke={isNavy ? '#FFFFFF' : design.ink}
              strokeWidth={4}
              strokeLinecap="round"
              strokeLinejoin="round"
              opacity={0.7}
            />
          ) : null}
        </svg>
      </div>
    </div>
  );
}

function pressureOf(e: { pressure: number; pointerType: string }) {
  // Mice report 0.5 while pressed; pens report real pressure.
  const p = e.pointerType === 'pen' ? e.pressure : 0.5;
  return Math.round(clamp(p || 0.5, 0.05, 1) * 100) / 100;
}
